#!/usr/bin/env python3
"""Tables and figure of the programme manifesto, generated from stored data (no number typed by hand).
Writes paper/tables_manifesto.tex and paper/fig_manifesto_n1.pdf."""
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
TRACK = HERE.parent
REPO = TRACK.parents[1]
AX1 = REPO / "experiments" / "axis1_topological_waves"


def load(p):
    return json.loads(Path(p).read_text())


n1 = load(AX1 / "evidence" / "n1_limit2.json")
c32 = load(TRACK / "data" / "depth_ordered_residuals_of_jacobian_columns.json")
c30 = load(TRACK / "data" / "jacobian_column_cloud_homology.json")
c33 = load(TRACK / "data" / "learned_persistence_features_of_jacobian_columns.json")
g1 = load(TRACK / "data" / "learned_persistence_features_g1_stratified.json")
lock = load(REPO / "lean" / "dtn_offsets" / "docs" / "statement_lock.json")
corpus = load(REPO / "papers" / "index.json")


def f3(x):
    return "%.3f" % x


def fig_n1():
    eps = n1["eps"]
    fig, ax = plt.subplots(1, 2, figsize=(8.6, 3.2))
    for kind, lab, st in (("chiral", "coupling disorder (chiral)", "o-"), ("onsite", "on-site terms", "s-"), ("nnn", "same-sublattice hopping", "^-")):
        ax[0].plot(eps, [n1["table"][f"topological|{kind}|{e}"]["median_E0"] for e in eps], st, label=lab)
        ax[1].plot(eps, [n1["table"][f"topological|{kind}|{e}"]["frac_WL_ge_0_9"] for e in eps], st, label=lab)
    ax[0].set_xscale("log"); ax[0].set_xlabel(r"perturbation strength $\varepsilon$"); ax[0].set_ylabel(r"median $|E_0|$ (gap $=1$)"); ax[0].legend(fontsize=7)
    ax[1].set_xscale("log"); ax[1].set_xlabel(r"$\varepsilon$"); ax[1].set_ylabel("fraction of draws with the mode at the left end")
    fig.tight_layout(); fig.savefig(HERE / "fig_manifesto_n1.pdf"); plt.close(fig)


def table_n1():
    eps = n1["eps"]
    rows = []
    for kind, lab in (("chiral", "coupling disorder (chiral)"), ("onsite", "on-site terms"), ("nnn", "same-sublattice hopping")):
        e0 = " & ".join("%.3f" % n1["table"][f"topological|{kind}|{e}"]["median_E0"] for e in eps)
        fr = " & ".join("%.2f" % n1["table"][f"topological|{kind}|{e}"]["frac_WL_ge_0_9"] for e in eps)
        rows.append(f"{lab}, median $|E_0|$ & {e0} \\\\")
        rows.append(f"{lab}, end fraction & {fr} \\\\")
    head = "Perturbation, statistic & " + " & ".join(str(e) for e in eps) + " \\\\ \\midrule"
    return "\n".join(["\\begin{table}[t]\\centering\\scriptsize",
                      "\\caption{Node N1, the finite SSH chain (41 sites, $v=1/2$, $w=1$, gap 1, 50 draws per cell): median energy of the mode closest to zero and fraction of draws in which it carries at least $90\\,\\%$ of its weight on the left quarter, against the perturbation strength. From \\texttt{evidence/n1\\_limit2.json} (the repeat run, whose gates pass).}",
                      "\\label{tab:n1}", "\\resizebox{\\linewidth}{!}{%", "\\begin{tabular}{l" + "c" * len(eps) + "}\\toprule", head, *rows, "\\bottomrule\\end{tabular}}\\end{table}"])


def table_base():
    sl = c32["slopes"]
    rows = [
        ("Conditioning of the DtN Jacobian, flat disk (preregistration 32)", f"$\\sigma_{{\\min}}$ falls {f3(-sl['sigma_min'])} decades per depth layer; the depth-ordered residual {f3(-sl['rho'])}"),
        ("Same, $\\{7,3\\}$ tiling", f"worst-column residual falls {f3(-c32['hyperbolic_73_L5']['slope_rho'])} per layer over four layers"),
        ("Nearest-neighbour persistence of the columns (preregistration 30)", f"median $H_0$ death time slope {f3(c30['square']['fit']['slope'])} per layer (a power law, post hoc)"),
        ("Learned persistence features (preregistration 33)", f"leak gate failed: shuffled-target models reach median $R^2$ {f3(g1['stratified']['median_r2'])} on the held-out disk; results unread"),
        ("Lean 4 (project \\texttt{dtn\\_offsets})", f"{sum(len(v) for v in lock.values())} locked declarations in three modules; 10 theorems on the three standard axioms"),
        ("Corpus", f"{len(corpus)} identity-checked papers in {len(set(p['pillar'] for p in corpus))} pillars in the vector store"),
    ]
    body = [f"{a} & {b} \\\\" for a, b in rows]
    return "\n".join(["\\begin{table}[t]\\centering\\small", "\\caption{The base the programme starts from, from the stored data and the repository state.}", "\\label{tab:base}",
                      "\\begin{tabular}{p{6.2cm}p{8.4cm}}\\toprule", "Item & Measured state \\\\ \\midrule", *body, "\\bottomrule\\end{tabular}\\end{table}"])


def main():
    fig_n1()
    (HERE / "tables_manifesto.tex").write_text("% GENERATED by make_manifesto.py from stored data -- do not edit\n" + table_n1() + "\n\n" + table_base() + "\n")
    print("wrote tables_manifesto.tex, fig_manifesto_n1.pdf; locked declarations:", sum(len(v) for v in lock.values()))


if __name__ == "__main__":
    main()
